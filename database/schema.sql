-- Run this file in the Supabase SQL Editor, or with psql using your Supabase connection string.


CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'cashier'
                  CHECK (role IN ('cashier', 'manager')),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)  NOT NULL,
    category   VARCHAR(50)   NOT NULL DEFAULT 'general',
    price      NUMERIC(10,2) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transactions (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cashier_id     INTEGER       NOT NULL,
    product_id     INTEGER       NOT NULL,
    quantity       INTEGER       NOT NULL,
    unit_price     NUMERIC(10,2) NOT NULL,
    total_amount   NUMERIC(10,2) NOT NULL,
    is_anomalous   BOOLEAN       NOT NULL DEFAULT FALSE,
    anomaly_reason VARCHAR(500)  DEFAULT NULL,
    reviewed       BOOLEAN       NOT NULL DEFAULT FALSE,
    reviewed_at    TIMESTAMP     NULL DEFAULT NULL,
    created_at     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (cashier_id) REFERENCES users(id),
    FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE INDEX IF NOT EXISTS idx_transactions_cashier_created
    ON transactions (cashier_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_transactions_created
    ON transactions (created_at DESC);
